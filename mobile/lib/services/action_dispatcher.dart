import 'dart:io' show Platform;
import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:android_intent_plus/android_intent.dart';
import 'package:url_launcher/url_launcher.dart';
import 'package:flutter_local_notifications/flutter_local_notifications.dart';
import '../models/action_model.dart';

/// Central Dispatcher for Device-Level Hardware Controls and Smart Deep Links
class ActionDispatcher {
  static final FlutterLocalNotificationsPlugin _notificationsPlugin =
      FlutterLocalNotificationsPlugin();

  static bool _notificationsInitialized = false;

  /// Initialize local notification subsystem for iOS & fallback alarms
  static Future<void> initialize() async {
    if (_notificationsInitialized) return;

    const androidSettings =
        AndroidInitializationSettings('@mipmap/ic_launcher');
    const iosSettings = DarwinInitializationSettings(
      requestAlertPermission: true,
      requestBadgePermission: true,
      requestSoundPermission: true,
    );

    const initSettings = InitializationSettings(
      android: androidSettings,
      iOS: iosSettings,
    );

    await _notificationsPlugin.initialize(initSettings);
    _notificationsInitialized = true;
  }

  /// Dispatches any action object generated by the Gemini Agent
  static Future<bool> dispatch(BuildContext context, ClientAction action) async {
    switch (action.type) {
      case ActionType.nativeAlarm:
        final hour = action.payload['hour'] as int? ?? 6;
        final minute = action.payload['minute'] as int? ?? 0;
        final label = action.payload['label'] as String? ?? 'Astra Alarm';
        final skipUi = action.payload['skip_ui'] as bool? ?? false;
        return await triggerNativeAlarm(
          context: context,
          hour: hour,
          minute: minute,
          label: label,
          skipUi: skipUi,
        );

      case ActionType.deepLink:
        final targetUrl = action.payload['target_url'] as String? ?? '';
        final fallbackWebUrl = action.payload['fallback_web_url'] as String? ?? '';
        final summary = action.payload['summary'] as String? ?? 'External Link';
        return await openSmartDeepLink(
          context: context,
          targetUrl: targetUrl,
          fallbackWebUrl: fallbackWebUrl,
          summary: summary,
        );

      case ActionType.scheduledReminder:
        final title = action.payload['title'] as String? ?? 'Reminder';
        final scheduledTime = action.payload['scheduled_time'] as String? ?? '';
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Proactive Reminder Scheduled: $title ($scheduledTime)'),
            backgroundColor: Colors.teal.shade700,
            behavior: SnackBarBehavior.floating,
          ),
        );
        action.executed = true;
        return true;

      default:
        debugPrint('Unknown action type: ${action.type}');
        return false;
    }
  }

  /// FEATURE A: Device-Level Hardware Controls (Native Alarm Execution)
  /// Invokes the Android OS Clock via Intent with EXTRA_HOUR, EXTRA_MINUTES, EXTRA_MESSAGE.
  /// Falls back to iOS Local Notification schedule on Apple devices.
  static Future<bool> triggerNativeAlarm({
    required BuildContext context,
    required int hour,
    required int minute,
    required String label,
    bool skipUi = false,
  }) async {
    try {
      if (!kIsWeb && Platform.isAndroid) {
        // Construct explicit Android Intent for Alarm Clock
        final intent = AndroidIntent(
          action: 'android.intent.action.SET_ALARM',
          arguments: <String, dynamic>{
            'android.intent.extra.alarm.HOUR': hour,
            'android.intent.extra.alarm.MINUTES': minute,
            'android.intent.extra.alarm.MESSAGE': label,
            'android.intent.extra.alarm.SKIP_UI': skipUi,
            'android.intent.extra.alarm.VIBRATE': true,
          },
        );

        await intent.launch();

        if (context.mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: Text(
                '⏰ Native Clock Alarm set for ${hour.toString().padLeft(2, '0')}:${minute.toString().padLeft(2, '0')} ($label)',
              ),
              backgroundColor: const Color(0xFF1E3A8A),
              behavior: SnackBarBehavior.floating,
              action: SnackBarAction(
                label: 'View Alarms',
                textColor: Colors.amber,
                onPressed: () => openClockApp(),
              ),
            ),
          );
        }
        return true;
      } else {
        // iOS / Web fallback: schedule high priority notification
        await initialize();
        final now = DateTime.now();
        var scheduledDate = DateTime(now.year, now.month, now.day, hour, minute);
        if (scheduledDate.isBefore(now)) {
          scheduledDate = scheduledDate.add(const Duration(days: 1));
        }

        const androidDetails = AndroidNotificationDetails(
          'astra_alarms',
          'Astra Alarms',
          channelDescription: 'High-priority native alarm channel',
          importance: Importance.max,
          priority: Priority.high,
          playSound: true,
        );
        const iosDetails = DarwinNotificationDetails(
          presentAlert: true,
          presentSound: true,
        );

        await _notificationsPlugin.show(
          101,
          '⏰ Alarm: $label',
          'Scheduled for ${hour.toString().padLeft(2, '0')}:${minute.toString().padLeft(2, '0')}',
          const NotificationDetails(android: androidDetails, iOS: iosDetails),
        );

        if (context.mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: Text('Alarm scheduled for ${hour.toString().padLeft(2, '0')}:${minute.toString().padLeft(2, '0')} ($label)'),
              backgroundColor: Colors.indigo.shade800,
            ),
          );
        }
        return true;
      }
    } catch (e) {
      debugPrint('Failed to set native alarm: $e');
      if (context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Could not invoke native clock: $e'),
            backgroundColor: Colors.red.shade700,
          ),
        );
      }
      return false;
    }
  }

  /// FEATURE B: Smart Deep-Linking for External Tasks (Movie & Booking Automation)
  /// Checks if native app scheme exists (bms://, swiggy://, uber://).
  /// Launches native app if installed, smoothly falling back to fallbackWebUrl with zero friction.
  static Future<bool> openSmartDeepLink({
    required BuildContext context,
    required String targetUrl,
    required String fallbackWebUrl,
    required String summary,
  }) async {
    try {
      final nativeUri = Uri.tryParse(targetUrl);
      final webUri = Uri.tryParse(fallbackWebUrl);

      bool launchedNative = false;

      // 1. Attempt to launch native app custom scheme
      if (nativeUri != null && await canLaunchUrl(nativeUri)) {
        launchedNative = await launchUrl(
          nativeUri,
          mode: LaunchMode.externalApplication,
        );
      }

      // 2. Fallback to HTTPS Web URL if native app not installed
      if (!launchedNative && webUri != null) {
        final launchedWeb = await launchUrl(
          webUri,
          mode: LaunchMode.externalApplication,
        );
        if (launchedWeb && context.mounted) {
          ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(
              content: Text('Opened $summary via Web Browser (Native app not installed)'),
              behavior: SnackBarBehavior.floating,
            ),
          );
          return true;
        }
      }

      if (launchedNative && context.mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Launched $summary in native app!'),
            backgroundColor: Colors.teal.shade800,
            behavior: SnackBarBehavior.floating,
          ),
        );
        return true;
      }

      return false;
    } catch (e) {
      debugPrint('Error launching deep link: $e');
      return false;
    }
  }

  /// Opens the default Android Clock application so user can inspect their alarms
  static Future<void> openClockApp() async {
    try {
      if (!kIsWeb && Platform.isAndroid) {
        const intent = AndroidIntent(
          action: 'android.intent.action.SHOW_ALARMS',
        );
        await intent.launch();
      }
    } catch (e) {
      debugPrint('Error opening clock app: $e');
    }
  }
}
